// Glyph box: 4 wide, 6 tall. Advance keeps a monospace rhythm, which suits
// the arcade HUD aesthetic and makes score counters stop jittering.
export const GLYPH_H = 6;
export const GLYPH_W = 4;
export const ADVANCE = 5.6;

/** Width of a string in em units (1 em == cap height). */
export function measureText(str, size, tracking = 0) {
  if (!str.length) return 0;
  const unit = size / GLYPH_H;
  return (str.length * (ADVANCE + tracking) - (ADVANCE + tracking) + GLYPH_W) * unit;
}

export function glyphFor(ch) {
  return G[ch] || G[ch.toUpperCase()] || null;
}

/**
 * Emit a string into a glow renderer.
 * align: -1 left, 0 centre, 1 right. baseline: -1 bottom, 0 middle, 1 top.
 */
export function drawText(r, str, x, y, size, color, opts = {}) {
  const {
    align = 0,
    baseline = 0,
    width = 0.09,
    intensity = 1,
    tracking = 0,
    rot = 0,
    glow = 3.2,
  } = opts;
  str = String(str);
  const unit = size / GLYPH_H;
  const total = measureText(str, size, tracking);
  let ox = align === -1 ? 0 : align === 1 ? -total : -total * 0.5;
  const oy = baseline === -1 ? 0 : baseline === 1 ? -size : -size * 0.5;
  const lw = width * size;
  const cs = Math.cos(rot);
  const sn = Math.sin(rot);

  for (let i = 0; i < str.length; i++) {
    const paths = glyphFor(str[i]);
    if (paths && paths.length) {
      for (let p = 0; p < paths.length; p++) {
        const pts = paths[p];
        for (let k = 0; k < pts.length - 2; k += 2) {
          let x0 = ox + pts[k] * unit;
          let y0 = oy + pts[k + 1] * unit;
          let x1 = ox + pts[k + 2] * unit;
          let y1 = oy + pts[k + 3] * unit;
          if (rot !== 0) {
            const a0 = x0 * cs - y0 * sn, b0 = x0 * sn + y0 * cs;
            const a1 = x1 * cs - y1 * sn, b1 = x1 * sn + y1 * cs;
            x0 = a0; y0 = b0; x1 = a1; y1 = b1;
          }
          r.seg(x + x0, y + y0, x + x1, y + y1, lw, color, intensity, glow);
        }
      }
    }
    ox += (ADVANCE + tracking) * unit;
  }
}
